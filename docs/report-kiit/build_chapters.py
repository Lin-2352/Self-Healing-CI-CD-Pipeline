"""Generate chapters/*.tex from the Markdown chapters in docs/report/chapters/.

Chapters written by hand for this report (01, 02, 03, 11, parts of 04 and 12) live in chapters/ already and are
not touched. Generated files start with the line "% GENERATED by build_chapters.py" and are overwritten.

    python docs/report-kiit/build_chapters.py
"""
import io, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import md2tex  # noqa: E402

SRC = os.path.join(os.path.dirname(HERE), "report", "chapters")
OUT = os.path.join(HERE, "chapters")
HEAD = "% GENERATED by build_chapters.py from docs/report/chapters/%s; edit the Markdown, not this file\n"


def md(name):
    return io.open(os.path.join(SRC, name), encoding="utf-8").read()


# output file -> (chapter title, [(markdown file, section title or None, demote)], inserts)
# inserts: (heading text to insert after, tex line)
PLAN = {
    "04_architecture": ("System Architecture", [("04_architecture.md", None, 0)],
                        [("Components", "\\input{figures/fig_architecture}"),
                         ("Diagram", ""),
                         ("Data flow of one heal", "\\input{figures/fig_dfd}")]),
    "05_github_actions": ("GitHub Actions and the Notify Job", [("05_github_actions.md", None, 0)], []),
    "06_n8n_workflow": ("The n8n Healing Workflow", [("06_n8n_healer.md", None, 0)],
                        [("Retry behaviour", "\\input{figures/fig_retry}")]),
    "07_model_endpoint": ("The Model Endpoint", [("07_model_endpoint.md", None, 0)],
                          [("Context ladder", "\\input{figures/fig_boot}")]),
    "08_backend": ("The ci-heal-backend Service", [("08_backend.md", None, 0)], []),
    "09_evaluation": ("Evaluation and Results", [("09_evaluation.md", None, 0),
                                                 ("10_live_run.md", "A Recorded Live Run", 1)],
                      [("What happened", "\\input{figures/fig_shots}")]),
    "10_security_testing": ("Security, Testing and Deployment", [("12_security.md", "Security", 1),
                                                                ("11_testing.md", "Testing and Verification", 1),
                                                                ("13_operation.md", "Deployment and Operation", 1)], []),
    "12a_limits_future": (None, [("14_limitations.md", "Current System Limitations", 1),
                                 ("15_future_work.md", "Future Enhancements", 1)], []),
    "appendix_a_structure": ("Repository Map and Directory Structure", [("16_repository_map.md", None, 0)], []),
}


def main():
    for key, (title, parts, inserts) in PLAN.items():
        body = ["% GENERATED by build_chapters.py; edit docs/report/chapters, not this file\n"]
        if title:
            body.append("\\chapter{%s}\n" % md2tex.inline(title))
        for fname, sec, demote in parts:
            if sec:
                body.append("\\section{%s}\n" % md2tex.inline(sec))
            body.append(md2tex.convert(md(fname), key.split("_")[0] + sec_id(sec), demote))
        text = "\n".join(body)
        for heading, line in inserts:
            marker = "{%s}\n" % md2tex.inline(heading)
            idx = text.find(marker)
            if idx >= 0:
                cut = idx + len(marker)
                if heading == "Diagram":        # the text diagram section is replaced by the TikZ figure
                    start = text.rfind("\\section", 0, idx)
                    nxt = text.find("\\section{", cut)
                    text = text[:start] + text[nxt:]
                    continue
                text = text[:cut] + "\n" + line + "\n" + text[cut:]
            else:
                print("insert target not found in %s: %s" % (key, heading))
        io.open(os.path.join(OUT, key + ".tex"), "w", encoding="utf-8", newline="\n").write(text)
        print("wrote chapters/%s.tex" % key)


def sec_id(sec):
    return "" if not sec else "".join(c for c in sec.lower() if c.isalpha())[:6]


if __name__ == "__main__":
    main()
